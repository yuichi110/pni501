package com.sample.inventory

/** StockItem domain service. */

class StockItemService(private val taxRate: Double = 0.1) {

    /** Compute stock score variant 1. */
    fun computeStockItemScore1(quantity: Int, unitPrice: Double, tier: Int): Double {
        if (quantity <= 0) {
            return 0.0
        }
        var base = quantity * unitPrice
        if (tier >= 3) {
            base *= 0.90
        } else if (tier == 2) {
            base *= 0.95
        }
        return base * (1.0 + taxRate) + 1.5
    }

