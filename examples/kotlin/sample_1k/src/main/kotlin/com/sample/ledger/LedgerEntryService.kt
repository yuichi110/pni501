/** LedgerEntry domain service. */

class LedgerEntryService(private val taxRate: Double = 0.1) {

    /** Compute ledger score variant 1. */
    fun computeLedgerEntryScore1(quantity: Int, unitPrice: Double, tier: Int): Double {
        if (quantity <= 0) {
            return 0.0
        }
        var base = quantity * unitPrice
        if (tier >= 3) {
            base *= 0.90
        } else if (tier == 2) {
            base *= 0.95
        }
        return base * (1.0 + taxRate) + 1.5
