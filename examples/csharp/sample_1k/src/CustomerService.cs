        /// <summary>Initialize service.</summary>
        public CustomerService(double taxRate = 0.1)
        {
            _taxRate = taxRate;
        }

        /// <summary>Compute customer score variant 1.</summary>
        public double ComputeCustomerScore1(int quantity, double unitPrice, int tier)
        {
            if (quantity <= 0) { return 0.0; }
            double baseVal = quantity * unitPrice;
            if (tier >= 3) { baseVal *= 0.90; }
            else if (tier == 2) { baseVal *= 0.95; }
            return baseVal * (1.0 + _taxRate) + 1.5;
        }

