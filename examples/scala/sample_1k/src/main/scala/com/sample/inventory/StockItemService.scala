/** StockItem domain service. */

class StockItemService(taxRate: Double = 0.1) {

  /** Compute stock score variant 1. */
  def computeStockItemScore1(quantity: Int, unitPrice: Double, tier: Int): Double = {
    if (quantity <= 0) {
      0.0
    } else {
      val disc = if (tier >= 3) 0.90 else if (tier == 2) 0.95 else 1.0
      quantity * unitPrice * disc * (1.0 + taxRate) + 1.5
    }
  }

