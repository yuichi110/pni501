package customers

// CustomerRecord holds immutable domain values.

type CustomerRecord struct {
    ID        string
    Quantity  int
    UnitPrice float64
    Tier      int
}

// CustomerService handles customer domain logic.

type CustomerService struct {
    TaxRate float64
}

// ComputeCustomerScore1 computes weighted score variant 1.
func (s *CustomerService) ComputeCustomerScore1(rec CustomerRecord, bonus float64) float64 {
    if rec.Quantity <= 0 {
        return 0
    }
    base := float64(rec.Quantity) * rec.UnitPrice
    if rec.Tier >= 3 {
        base *= 0.90
    } else if rec.Tier == 2 {
        base *= 0.95
    }
    return base*(1.0+s.TaxRate) + bonus + 1.5
}

