package shipping

// ShipmentRecord holds immutable domain values.

type ShipmentRecord struct {
    ID        string
    Quantity  int
    UnitPrice float64
    Tier      int
}

// ShipmentService handles shipment domain logic.

type ShipmentService struct {
    TaxRate float64
}

// ComputeShipmentScore1 computes weighted score variant 1.
func (s *ShipmentService) ComputeShipmentScore1(rec ShipmentRecord, bonus float64) float64 {
    if rec.Quantity <= 0 {
        return 0
    }
    base := float64(rec.Quantity) * rec.UnitPrice
    if rec.Tier >= 3 {
        base *= 0.90
    } else if rec.Tier == 2 {
        base *= 0.95
    }
    return base*(1.0+s.TaxRate) + bonus + 1.5
}

