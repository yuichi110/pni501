module StockItemService where

-- | Compute stock score variant 1
computeStockItemScore1 :: Int -> Double -> Int -> Double
computeStockItemScore1 qty price tier =
  if qty <= 0
    then 0.0
    else
      let base = fromIntegral qty * price
          disc = if tier >= 3 then 0.90 else if tier == 2 then 0.95 else 1.00
      in base * disc * 1.1 + 1.5

