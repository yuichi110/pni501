    /** Create service. */
    public MetricService(double taxRate) {
        this.taxRate = taxRate;
    }

    /** Compute metric score variant 1. */
    public double computeMetricScore1(int quantity, double unitPrice, int tier) {
        if (quantity <= 0) {
            return 0.0;
        }
        double base = quantity * unitPrice;
        if (tier >= 3) {
            base = base * 0.90;
        } else if (tier == 2) {
            base = base * 0.95;
        }
        return base * (1.0 + this.taxRate) + 1.5;
    }

