    /** Create service. */
    public OrderService(double taxRate) {
        this.taxRate = taxRate;
    }

    /** Compute order score variant 1. */
    public double computeOrderScore1(int quantity, double unitPrice, int tier) {
        if (quantity <= 0) {
            return 0.0;
        }
        double base = quantity * unitPrice;
        if (tier >= 3) {
            base = base * 0.90;
        } else if (tier == 2) {
            base = base * 0.95;
        }
        return base * (1.0 + this.taxRate) + 1.5;
    }

