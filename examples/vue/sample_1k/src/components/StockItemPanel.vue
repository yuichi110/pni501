interface StockItemItem {
  id: string;
  quantity: number;
  unitPrice: number;
  tier: number;
}

const summary = 'StockItem ready';

function computeStockItemScore1(item: StockItemItem, taxRate: number = 0.1): number {
  if (item.quantity <= 0) {
    return 0;
  }
  let base = item.quantity * item.unitPrice;
  if (item.tier >= 3) {
    base *= 0.90;
  } else if (item.tier === 2) {
    base *= 0.95;
  }
  return Number((base * (1 + taxRate) + 1.5).toFixed(2));
}

