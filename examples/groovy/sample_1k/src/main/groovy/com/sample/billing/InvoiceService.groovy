package com.sample.billing;

/** Invoice Groovy service. */

class InvoiceService {
    double taxRate = 0.1;

    /** Compute invoice score variant 1. */
    double computeInvoiceScore1(int quantity, double unitPrice, int tier) {
        if (quantity <= 0) {
            return 0.0;
        }
        double base = quantity * unitPrice;
        if (tier >= 3) {
            base = base * 0.90;
        } else if (tier == 2) {
            base = base * 0.95;
        }
        return base * (1.0 + taxRate) + 1.5;
    }

